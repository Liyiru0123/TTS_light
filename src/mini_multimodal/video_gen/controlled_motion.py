"""Explicit motion control for LDM-generated appearance anchors.

The object appearance is generated by the frozen P2-W04 image LDM.  This
module only propagates that generated latent residual according to an
explicit frame-wise motion condition.  It never rasterizes a target shape.
"""

from __future__ import annotations

import torch
from torch import nn
import torch.nn.functional as F


def motion_controls(trajectory: torch.Tensor, threshold: float = 0.015) -> tuple[torch.Tensor, torch.Tensor]:
    """Return per-frame velocity and moving/static state.

    ``trajectory`` is ``[B,F,2]`` in normalized image coordinates.  Velocity
    at frame ``t`` describes the transition from ``t-1`` to ``t``; frame zero
    is always static.
    """
    if trajectory.ndim != 3 or trajectory.shape[-1] != 2:
        raise ValueError("trajectory must have shape [B,F,2]")
    velocity = torch.zeros_like(trajectory)
    velocity[:, 1:] = trajectory[:, 1:] - trajectory[:, :-1]
    moving = velocity.norm(dim=-1, keepdim=True).gt(float(threshold)).to(trajectory.dtype)
    return velocity, moving


class ControlledTemporalAttention(nn.Module):
    """AnimateDiff-style temporal attention with explicit motion state.

    The two reshapes are intentionally kept visible for teaching:
    ``[B,C,F,H,W] -> [B*H*W,F,C] -> [B,C,F,H,W]``.
    A zero-initialized residual gate makes the module safe to insert before
    training; the explicit motion field remains independently testable.
    """

    def __init__(self, channels: int = 4, heads: int = 1, ff_mult: int = 4) -> None:
        super().__init__()
        if channels % heads:
            raise ValueError("channels must be divisible by heads")
        self.control = nn.Linear(5, channels)
        self.attention = nn.MultiheadAttention(channels, heads, batch_first=True)
        self.norm2 = nn.LayerNorm(channels)
        self.ff = nn.Sequential(
            nn.Linear(channels, channels * ff_mult),
            nn.GELU(),
            nn.Linear(channels * ff_mult, channels),
        )
        self.output_gate = nn.Parameter(torch.zeros(channels))
        self._initialize_safe_temporal_average()

    def _initialize_safe_temporal_average(self) -> None:
        """Start from a gated uniform temporal average proposal.

        The externally visible module is still identity because the residual
        gate is zero.  Once trained, attention can first learn the useful and
        stable operation of averaging aligned generated features over frames.
        """
        channels = self.attention.embed_dim
        with torch.no_grad():
            self.control.weight.zero_()
            self.control.bias.zero_()
            self.attention.in_proj_weight.zero_()
            self.attention.in_proj_bias.zero_()
            self.attention.in_proj_weight[2 * channels:3 * channels].copy_(torch.eye(channels))
            self.attention.out_proj.weight.copy_(torch.eye(channels))
            self.attention.out_proj.bias.zero_()
            self.ff[-1].weight.zero_()
            self.ff[-1].bias.zero_()

    def forward(self, video: torch.Tensor, trajectory: torch.Tensor) -> torch.Tensor:
        if video.ndim != 5:
            raise ValueError("video must have shape [B,C,F,H,W]")
        batch, channels, frames, height, width = video.shape
        if trajectory.shape != (batch, frames, 2):
            raise ValueError("trajectory/video shape mismatch")
        velocity, moving = motion_controls(trajectory)
        control = torch.cat((trajectory, velocity, moving), dim=-1)

        # Dimension transform 1: one temporal sequence for every spatial site.
        base = video.permute(0, 3, 4, 2, 1).reshape(batch * height * width, frames, channels)
        condition = self.control(control)[:, None, None].expand(batch, height, width, frames, channels)
        condition = condition.reshape(batch * height * width, frames, channels)
        hidden = base + condition
        proposal, _ = self.attention(hidden, hidden, hidden)
        proposal = proposal + self.ff(self.norm2(proposal))
        gate = torch.tanh(self.output_gate)[None, None, :]
        hidden = base + gate * (proposal - base)

        # Dimension transform 2: restore video layout.
        return hidden.reshape(batch, height, width, frames, channels).permute(0, 4, 3, 1, 2)


def propagate_generated_residual(
    anchor: torch.Tensor,
    background: torch.Tensor,
    foreground_mask: torch.Tensor,
    trajectory: torch.Tensor,
) -> torch.Tensor:
    """Move an LDM-generated foreground residual with a differentiable flow.

    Inputs are latent-space tensors.  ``foreground_mask`` is an observation of
    the generated anchor, not a programmatic target-shape mask.
    """
    if anchor.ndim != 4 or background.shape != anchor.shape:
        raise ValueError("anchor/background must share [B,C,H,W]")
    batch, _, height, width = anchor.shape
    if foreground_mask.shape != (batch, 1, height, width):
        raise ValueError("foreground_mask must have shape [B,1,H,W]")
    if trajectory.ndim != 3 or trajectory.shape[0] != batch or trajectory.shape[-1] != 2:
        raise ValueError("trajectory must have shape [B,F,2]")

    frames = trajectory.shape[1]
    aligned_video = anchor[:, :, None].expand(-1, -1, frames, -1, -1)
    return propagate_aligned_video(aligned_video, background, foreground_mask, trajectory)


def propagate_aligned_video(
    aligned_video: torch.Tensor,
    background: torch.Tensor,
    foreground_mask: torch.Tensor,
    trajectory: torch.Tensor,
) -> torch.Tensor:
    """Warp a frame-wise, anchor-aligned generated appearance sequence."""
    if aligned_video.ndim != 5:
        raise ValueError("aligned_video must have shape [B,C,F,H,W]")
    batch, _, frames, height, width = aligned_video.shape
    if background.shape != aligned_video.shape[:2] + aligned_video.shape[3:]:
        raise ValueError("background/aligned_video shape mismatch")
    if foreground_mask.shape != (batch, 1, height, width):
        raise ValueError("foreground_mask must have shape [B,1,H,W]")
    if trajectory.shape != (batch, frames, 2):
        raise ValueError("trajectory/aligned_video shape mismatch")
    residual = (aligned_video - background[:, :, None]) * foreground_mask[:, :, None]
    delta = trajectory - trajectory[:, :1]
    yy, xx = torch.meshgrid(
        torch.linspace(-1.0, 1.0, height, device=aligned_video.device, dtype=aligned_video.dtype),
        torch.linspace(-1.0, 1.0, width, device=aligned_video.device, dtype=aligned_video.dtype),
        indexing="ij",
    )
    base_grid = torch.stack((xx, yy), dim=-1)[None, None].expand(batch, frames, height, width, 2).clone()
    base_grid[..., 0] -= 2.0 * delta[..., 0, None, None]
    base_grid[..., 1] -= 2.0 * delta[..., 1, None, None]
    flat_grid = base_grid.reshape(batch * frames, height, width, 2)
    flat_residual = residual.permute(0, 2, 1, 3, 4).reshape(batch * frames, -1, height, width)
    moved = F.grid_sample(flat_residual, flat_grid, mode="bilinear", padding_mode="zeros", align_corners=True)
    moved = moved.reshape(batch, frames, -1, height, width).permute(0, 2, 1, 3, 4)
    return background[:, :, None] + moved


class GeneratedAppearanceMotionModule(nn.Module):
    """Generated appearance + explicit motion field + temporal attention."""

    def __init__(self, latent_channels: int = 4) -> None:
        super().__init__()
        self.temporal = ControlledTemporalAttention(channels=latent_channels, heads=1)

    def forward(
        self,
        anchor: torch.Tensor,
        background: torch.Tensor,
        foreground_mask: torch.Tensor,
        trajectory: torch.Tensor,
        *,
        use_temporal_attention: bool = True,
        aligned_video: torch.Tensor | None = None,
    ) -> torch.Tensor:
        frames = trajectory.shape[1]
        aligned = (
            anchor[:, :, None].expand(-1, -1, frames, -1, -1)
            if aligned_video is None else aligned_video
        )
        if use_temporal_attention:
            aligned = self.temporal(aligned, trajectory)
        return propagate_aligned_video(aligned, background, foreground_mask, trajectory)
